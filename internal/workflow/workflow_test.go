// Only the external LLM is substituted; workers, activities and both SQLite
// databases are real. The result must identify the persisted run, not the
// workflow instance. Byte counts must not become Unicode character counts;
// handled failures and a concurrent cancellation must reflect persisted state,
// not the text generated by the engine or the workflow's completion status.
func TestSummaryWorkflowResultReferencesStoredRun(t *testing.T) {
	for _, tc := range []struct {
		name         string
		status       string
		summaryBytes int
		errorCode    string
	}{
		{"success", domain.StatusSucceeded, 9, ""},
		{"engine failure", domain.StatusFailed, 0, "engine_failed"},
		{"cancelled during engine execution", domain.StatusCancelled, 0, ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			s, err := store.New(filepath.Join(dir, "app.db"))
			if err != nil {
				t.Fatal(err)
			}
			defer s.Close()
			runID := "b4203f9d-d8ba-4a17-b922-98442950f240"
			if err := s.CreateRun(&domain.Run{
				ID: runID, Status: domain.StatusQueued, Stage: domain.StageQueued,
				InputType: domain.InputTypeText, InputText: "A short source document.",
				Engine: domain.EnginePi, Format: domain.FormatSummary,
			}); err != nil {
				t.Fatal(err)
			}
			summaryworkflow.SetDeps(summaryworkflow.Deps{
				Store: s, Config: &config.Config{DataDir: dir, MaxInputChars: 10000, RunTimeout: time.Second},
				PiEngine: &fixtureEngine{status: tc.status, store: s},
			})
			defer summaryworkflow.SetDeps(summaryworkflow.Deps{})
			b := sqlite.NewSqliteBackend(filepath.Join(dir, "workflows.db"))
			defer b.Close()
			w := worker.New(b, nil)
			if err := w.RegisterWorkflow(summaryworkflow.SummaryWorkflow); err != nil {
				t.Fatal(err)
			}
			for _, activity := range []any{
				summaryworkflow.MarkRunningActivity, summaryworkflow.LoadRunActivity,
				summaryworkflow.LoadSummaryResultActivity,
				summaryworkflow.SummarizeActivity, summaryworkflow.FailRunActivity,
			} {
				if err := w.RegisterActivity(activity); err != nil {
					t.Fatal(err)
				}
			}
			ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
			if err := w.Start(ctx); err != nil {
				cancel()
				t.Fatal(err)
			}
			defer func() { cancel(); _ = w.WaitForCompletion() }()
			c := client.New(b)
			instance, err := c.CreateWorkflowInstance(ctx, client.WorkflowInstanceOptions{
				InstanceID: "summary:txt:pi:b4203f9d",
			}, summaryworkflow.SummaryWorkflow, summaryworkflow.SummaryWorkflowInput{RunID: runID})
			if err != nil {
				t.Fatal(err)
			}
			result, err := client.GetWorkflowResult[map[string]any](ctx, c, instance, 15*time.Second)
			if err != nil {
				t.Fatal(err)
			}
			if result["run_id"] != runID || result["status"] != tc.status || result["summary_bytes"] != float64(tc.summaryBytes) {
				t.Fatalf("result = %#v, want run_id %q, status %q, summary_bytes %d", result, runID, tc.status, tc.summaryBytes)
			}
			wantFields := 3
			if tc.errorCode != "" {
				wantFields++
				if result["error_code"] != tc.errorCode {
					t.Fatalf("error_code = %#v, want %q", result["error_code"], tc.errorCode)
				}
			} else if _, present := result["error_code"]; present {
				t.Fatalf("unexpected error_code in %s result: %#v", tc.status, result)
			}
			if len(result) != wantFields {
				t.Fatalf("result contains unexpected fields: %#v", result)
			}
			run, err := s.GetRun(runID)
			if err != nil {
				t.Fatal(err)
			}
			if run.Status != tc.status || run.ErrorCode != tc.errorCode {
				t.Fatalf("referenced run = %s/%s, want %s/%s", run.Status, run.ErrorCode, tc.status, tc.errorCode)
			}
			if tc.status == domain.StatusSucceeded && run.Summary != "Café ☕" {
				t.Fatalf("stored summary = %q, want Café ☕", run.Summary)
			} else if tc.status != domain.StatusSucceeded && run.Summary != "" {
				t.Fatalf("non-successful run stored a summary: %q", run.Summary)
			}
		})
	}
}

type fixtureEngine struct {
	status string
	store  *store.Store
}

func (*fixtureEngine) Name() string { return domain.EnginePi }

func (e *fixtureEngine) Run(_ context.Context, req engine.Request) (engine.Result, error) {
	if e.status == domain.StatusFailed {
		return engine.Result{}, errors.New("fixture engine unavailable")
	}
	if e.status == domain.StatusCancelled {
		if err := e.store.CancelRun(req.RunID); err != nil {
			return engine.Result{}, err
		}
	}
	return engine.Result{Text: "Café ☕"}, nil
}
